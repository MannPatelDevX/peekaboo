import { invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import type { PromptRoute, AlwaysRule, AppState, ClaudexAction, ClaudexSnapshot, Decision, GroupData, TranscriptRow } from "./types";

export const getState = () => invoke<AppState>("get_state");
export const decide = (id: string, decision: Decision) => invoke<void>("decide", { id, decision });
export const installHooks = (agent: string) => invoke<void>("install_hooks", { agent });
export const uninstallHooks = (agent: string) => invoke<void>("uninstall_hooks", { agent });
export const removeRule = (rule: AlwaysRule) => invoke<void>("remove_rule", { rule });
export const getNotch = () => invoke<{ height: number; width: number }>("get_notch");
export type WindowSize = "collapsed" | "panel" | "board";
export const setSize = (size: WindowSize) => invoke<void>("set_size", { size });
export const onStateChanged = (cb: () => void) => listen("state:changed", () => cb());
export const onToggle = (cb: () => void) => listen("overlay:toggle", () => cb());
export const listTranscripts = () => invoke<TranscriptRow[]>("list_transcripts");
export const resumeSession = (id: string) => invoke<void>("resume_session", { id });
export const claudexSnapshot = (force: boolean) => invoke<ClaudexSnapshot>("claudex_snapshot", { force });
export const claudexAct = (action: ClaudexAction) => invoke<string>("claudex_act", { action });
export const getGroups = () => invoke<GroupData>("get_groups");
export const createGroup = (name: string) => invoke<GroupData>("create_group", { name });
export const renameGroup = (id: string, name: string) => invoke<GroupData>("rename_group", { id, name });
export const deleteGroup = (id: string) => invoke<GroupData>("delete_group", { id });
export const assignSession = (session: string, group: string | null) => invoke<GroupData>("assign_session", { session, group });
export const autoGroup = () => invoke<GroupData>("auto_group");
export const sendPrompt = (key: string, text: string) => invoke<PromptRoute>("send_prompt", { key, text });
export const setListening = (key: string, on: boolean) => invoke<void>("set_listening", { key, on });
